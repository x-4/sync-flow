// ====================================================================
// 固化常量：本文件里的每一项**曾经**是环境变量，现在刻意不再支持
// 环境变量覆盖。
//
// ── 为什么要把它们固化 ──────────────────────────────────────────
//
// 配置面曾经有 71 个环境变量（lib/config.js 读取的键，不含平台注入的
// 端口变量）。部署时它们全都要在平台的环境变量面板里逐条维护，而其中
// 绝大多数从第一次写下就没有被任何人改过——原因不是"默认值取得好"，
// 而是**它们本来就只有一个合理取值**：
//
//   · 改了只会更糟（UDP_QUERY_BURST 调小 → 浏览器首屏解析被拒；
//     SYNC_MAX_PAYLOAD 调大 → 内存放大上界抬到 3.2GB）；
//   · 属于内部实现细节（SYNC_DATAGRAM_COMPACT_MIN 是缓冲压实的阈值，
//     与"这次部署长什么样"毫无关系）；
//   · 取值由协议或实测钉死（UDP_MAX_QUERY_SIZE=4096 覆盖 EDNS0；
//     SYNC_STREAM_HWM=256KB 是实测吞吐最优点）。
//
// 把这些项留在面板上的实际效果是**负的**：多一个可填的格子，就多一处
// "填错/留空"的机会；而本项目已经因为"变量存在但为空"这类形态付出过
// 极高的排查成本（见 SYNC_UDP_DISABLE 与 TELEMETRY_ENDPOINTS 的注释）。
//
// ── 保留成环境变量的是哪些 ──────────────────────────────────────
//
// 只留与"这次部署长什么样"有关的：令牌（UUID / DIAG_TOKEN /
// DEVICE_TOKEN）、端点路径（SYNC_PATHS）、解析后端
// （TELEMETRY_ENDPOINTS）、并发规模（MAX_TOTAL_CONNECTIONS /
// MAX_PENDING_PER_IP / DEPLOY_INSTANCES）、功能开关（SYNC_UDP_DISABLE /
// SYNC_TARGET_GUARD / LOGIN_REQUIRED / SYNC_COMPAT_MODE）。这些在不同
// 部署之间确实不同，因此保留可配。完整清单见 .env.example。
//
// ── 固化后要怎么改 ──────────────────────────────────────────────
//
// 改本文件里的值，然后重新部署。这是刻意的：固化项一旦能在面板上改，
// "改一下试试"就会变成排障的第一反应，而这些值恰恰是标定过的——
// 让它们难以改动，等于把标定结果保护起来。
//
// ⚠️ 本文件里的每一项取值都与固化前的默认值**逐字相等**。这是一次
//    "取值来源"重构，不是调参；改动任何一项都必须先说明它会让哪条
//    既有标定失效。
//
// ── 下游不受影响 ────────────────────────────────────────────────
//
// lib/config.js 仍然把它们挂在同一套 CONFIG 字段上（CONFIG.XXX），
// 下游代码一律读 CONFIG，因此固化对调用方零影响。
// ====================================================================

'use strict';

const path = require('path');

const DEFAULTS = {
    // ==================================================================
    // 进程编排与存储
    // ==================================================================

    // 监听地址。留空 = 不指定（等价于双栈 ::，IPv4 与 IPv6 都能进），
    // 这是最兼容的取值：内网直连与外网经代理转发都不受影响。
    //
    // 固化理由：只有一个合理取值。收窄绑定范围（多网卡机器上避免监听
    // 到不该暴露的接口）是网络拓扑问题，应当改这里重新部署，而不是留
    // 一个"填错就变成只监听某个地址、其它来源全部连不上"的面板格子。
    LISTEN_HOST: '',

    // 数据落盘驱动。决定 store 层如何持久化业务数据：
    //   fs     —— 默认。读写本地文件系统（原子写：临时文件 + rename）。
    //             适用于自建机、Docker、K8s（挂载持久卷）等有可写磁盘的场景。
    //   memory —— 进程内内存表。不做任何磁盘 IO。
    //             适用于只读文件系统（Serverless / 边缘运行时）或
    //             明确不需要跨重启持久化的短生命周期场景。
    // 两种驱动对外接口完全一致，调用方无需感知；进程重启后 memory
    // 驱动的数据会丢失，这是该模式的固有语义而非缺陷。
    //
    // 固化理由：它不再是"部署者的选择"，而是**由运行形态推导出来的**
    // （Serverless 平台 → memory，常驻部署 → fs，见 config.js 的
    // SERVERLESS 判定）。曾经它可配，于是"以为用了内存驱动、实际在只读
    // 盘上疯狂报 EROFS"成为一个真实存在的部署事故形态；拼错驱动名
    // （STORAGE_DRIVER=mem）更是会静默走 fs 分支。现在由形态推导，
    // 这类事故从根上消失。
    STORAGE_DRIVER: 'fs',

    // 进程编排模式：false = 主进程 fork 出四个业务子进程（默认）。
    // 多核利用充分，单个业务崩溃不影响其他进程，适合自建机 / Docker /
    // K8s。true = 全部业务在主进程内顺序加载（require），不起子进程，
    // 面向 fork 受限或需要单进程模型的平台（Serverless / 边缘运行时）。
    // 业务与协议实现完全不变，仅改编排方式。
    //
    // 固化理由：与 STORAGE_DRIVER 同源——它由运行形态推导，不是偏好。
    // 且它与存储驱动之间存在硬约束（memory 驱动必须单进程，否则各
    // worker 的内存表互不可见），留两个可配项就等于留一个可以配出
    // 非法组合的面板。
    SINGLE_PROCESS: false,

    // 业务数据落盘目录（各业务进程真实产出/消费此处的数据）。
    //
    // 固化理由：内部路径细节，与部署形态无关。Serverless 形态下会被
    // config.js 按平台的可写临时目录改写（见 SERVERLESS_DATA_DIR_NAME）。
    DATA_DIR: path.join(__dirname, '..', 'data'),

    // Serverless 形态下的可写目录名（拼在平台的 TMPDIR 之后）。
    // 少数平台允许 /tmp 写入（Vercel 的 /tmp 是可写的），用它避免任何
    // 仍会触碰 DATA_DIR 的代码路径在启动期抛 EACCES。
    //
    // 固化理由：平台兜底目录的名字，纯内部细节。
    SERVERLESS_DATA_DIR_NAME: 'aether-data',

    // ==================================================================
    // 进程间事件总线
    // ==================================================================

    // 缓存预热进程通过该端口把快照推送给网关进程，供其对外提供实时库存。
    // 仅监听回环地址，不对外暴露，也不参与任何外部连接的处理。
    //
    // 固化理由：内部进程间通信端口，与部署形态无关；它唯一需要避让的是
    // 对外端口（config.js 的交叉校验会拦），而那不需要人来参与。
    EVENT_BUS_PORT: 3001,
    // 事件总线端点路径。
    //
    // 固化理由：内部端点路径，对外不可达，改它没有意义。
    EVENT_BUS_ENDPOINT: '/internal/cache-feed',
    // 总线断连后的重连间隔（毫秒）。
    //
    // 此前是内联在 event-bus.js 里的字面量 2000。收编进配置的理由不是
    // "想调它"，而是"排障时要能看见它"：总线抖动导致的快照陈旧，
    // 第一手信息就是这个重连节拍，它不该藏在代码里。
    //
    // 固化理由：排障时"能看见"这一点已由启动摘要与代码注释满足，而
    // 节拍本身是内部实现细节——改快改慢都不改变语义，只会改变抖动时的
    // 恢复速度。
    EVENT_BUS_RECONNECT_MS: 2000,

    // ==================================================================
    // 并发规模（与保留的 MAX_TOTAL_CONNECTIONS 的派生关系）
    // ==================================================================

    // 单 IP 并发上限 = 全局上限 / 该除数。
    //
    // 默认取全局上限的 1/2（100）。理由：全局上限管的是"整台机器能承载
    // 多少条连接"，管不到"这些连接是否被单一来源独占"。默认关闭时
    // （此前为 0），实测**一个来源即可建立全部 200 条连接**——即单个
    // 恶意或配置错误的客户端就能让所有真实用户连不上，恰好击穿
    // "客户端必须始终可连"这条底线。
    //
    // ── 为什么从 1/4 抬到 1/2（2026-09-24 标定）──────────────────
    //
    // 1/4 是按"一个 ERP 客户端开少数几条通道"标定的，对一个浏览器用户
    // 完全不适用：浏览器加载一屏页面时会在一个 RTT 窗口内开出几十条
    // 隧道并**同时持有**它们（页面并行请求 + 预连接 + DNS），而真连接
    // 测试只开 1 条、Telegram 只开 2~3 条——两者都远在墙内，于是
    // "测试全绿、浏览器不可用"能一直撑到第三轮排查才定位。
    //
    // 抬到 1/2 的代价极低，原因是它的上界由别人兜着：
    //   · SYNC_FIRST_BATCH_TIMEOUT（30s）会自动回收废弃连接，
    //     占着名额不发首包的连接撑不过这个窗口；
    //   · MAX_TOTAL_CONNECTIONS 是真正的硬上界，per-IP 只决定"这 200
    //     条里最多有多少条能被同一个来源拿走"。
    //
    // 那为什么不再抬到 = 全局上限：那样就等价于关闭按来源隔离（见
    // validateConfig：per-IP ≥ total 会被收敛并告警）。1/2 是"单点
    // 不能独占"这条性质还能成立的最大值。
    //
    // PaaS 在前端终结 TLS 后所有用户共用同一内网出口 IP，此时按 IP
    // 计数会按"全体用户"聚合——这恰恰是抬到 1/2 的第二个理由：共用
    // 出口下 per-IP 档就是全局档，取值过小会误伤所有人。
    //
    // 固化理由：它是一个**比例**，不是一项独立决策。真正随部署变化的
    // 是分子（MAX_TOTAL_CONNECTIONS，已保留为环境变量）；把比例也开放
    // 出去，等于允许配出"per-IP ≥ 全局"这种等价于关闭隔离的组合，
    // 而配置校验随后又会把它收敛回来——可配、但配了不算数，比不可配
    // 更糟。
    MAX_CONNECTIONS_PER_IP_DIVISOR: 2,

    // "已握手但首包未到"的全局连接上限（pending 档）。
    //
    // 这类连接还没证明自己是合法客户端，却占着资源：此前的实现让它们
    // 直接计入正式名额，于是"连上什么都不发"就能占满 200，靠首包超时
    // 前的循环重连可长期占死连接表。
    //
    // ── 取值标定（2026-09-24，按"浏览器首屏"重新标定）────────────
    //
    // 原值 40 是按"一个 ERP 客户端开少数几条通道"标定的。实测一个浏览器
    // 用户在一个 RTT 窗口内发起的合法握手是**几十条**量级：页面并行
    // 请求 + 预连接 + 每条域名解析各开一条隧道。而这套上限当时只有
    // 10/40，于是无论并发多少都"永远只有这么多条能过"——一堵硬墙，
    // 不是性能衰减。
    //
    // 症状之所以是"浏览器报 DNS 找不到"：被 429 拒掉的正是浏览器要开的
    // 第一批隧道，其中第一条就是 DNS；而真连接测试只开 1 条、Telegram
    // 只开 2~3 条，都在墙内。三轮排查都扑空，正是因为墙太矮。
    //
    // 抬到 128 的依据：覆盖"两三个用户同时首屏"，并留出一倍余量给
    // 预连接抖动与多标签页。
    //
    // 抬高的代价极低——**真正兜底的不是这个数**：
    //   · SYNC_FIRST_BATCH_TIMEOUT（30s）会自动回收废弃连接，pending
    //     名额最迟 30s 归还，靠循环重连长期占死通道表不可行；
    //   · MAX_TOTAL_CONNECTIONS 仍是全局硬上界（闸门判的是
    //     total + pending ≥ MAX_TOTAL_CONNECTIONS），pending 档怎么抬都
    //     不可能突破它。
    //
    // 固化理由：与 MAX_CONNECTIONS_PER_IP 同源——它是"一条机器能承受
    // 多少条未证明自己的连接"这个**标定值**，不是部署规模参数。规模
    // 那一方面由保留的 MAX_TOTAL_CONNECTIONS / DEPLOY_INSTANCES 表达。
    MAX_PENDING_TOTAL: 128,

    // 是否信任反向代理传递的 X-Forwarded-For 首跳作为客户端 IP。
    //
    // 运维提示（PaaS 部署）：平台在前端终结 TLS 后，所有外部用户共用
    // 同一内网出口 IP。此时若启用了按 IP 的限制（并发上限 / 限流桶），
    // 这些阈值是**全体用户的聚合上限**。当前默认值远高于真实用量，
    // 无需调整。
    //
    // 固化理由：这是"本服务前面有没有可信反代"这个**拓扑事实**，不是
    // 偏好；而 PaaS 上的 X-Forwarded-For 首跳是否可信，取决于平台是否
    // 会覆盖客户端伪造的头——在已知部署目标上它是确定的。留成开关的
    // 唯一效果是让人在"关着"（默认）时按 IP 计数聚合到出口 IP 上，误
    // 以为看到了真实来源。
    SYNC_TRUST_PROXY: false,

    // ==================================================================
    // 非法批次退避
    // ==================================================================

    // 窗口内同一来源累计到该值即进入冷却。
    INVALID_BATCH_THRESHOLD: 20,
    // 统计窗口（毫秒）。
    INVALID_BATCH_WINDOW: 60000,
    // 冷却时长（毫秒）。必须大于统计窗口，否则退避会在窗口结束前失效、
    // 语义倒置（config.js 的交叉校验会自动收敛）。
    //
    // 固化理由（三项一并）：这三个数描述的是"什么叫异常客户端"，属于
    // 对抗策略的内部标定；开放出去只能往松或往紧两个方向动，往松等于
    // 放弃抗扫描，往紧会误伤共用出口 IP 的全体用户。真正的部署差异
    // （是否连坐）由下面一项表达。
    INVALID_COOLDOWN: 300000,

    // 非法批次退避是否按"来源 IP"隔离（默认开启，即按 IP 连坐）。
    //
    // 这是一个明确的取舍，不是疏漏——用"共享 IP 下可能波及其它用户"
    // 换取"分布式扫描者无法靠更换连接规避计数"。在 PaaS 拓扑下
    // （所有用户共用同一内网出口 IP），一旦被单个异常客户端触发，
    // 该来源的全部用户会一起被拒 INVALID_COOLDOWN 毫秒，表现为
    // "莫名其妙都连不上，过几分钟又自己好了"。
    //
    // 固化理由：连坐与否是这套对抗策略的**固有语义**，不是部署选项。
    // 曾经它可配（INVALID_BATCH_PER_IP=0 收敛到单条连接），而"关掉
    // 连坐"意味着扫描者可以靠不断新建连接规避按连接计数——那一层由
    // HTTP_PACE 与并发上限管，关掉它只是把防护面缩小。保留默认值。
    INVALID_BATCH_PER_IP: true,

    // ==================================================================
    // 传输层保活
    // ==================================================================

    // 注意这里做的是 **TCP keepalive**，不是 WebSocket 的 ping 帧。
    // 两者有本质区别：
    //   TCP keepalive —— OS 层探测包，对 WS 帧层完全不可见。
    //     它只影响"中间设备是否认为这条连接还活着"（NAT 表项超时、
    //     PaaS 负载均衡的空闲回收），不产生任何可被观测的 WS 层特征。
    //   WS ping 帧 —— 协议层帧，会被任何解析帧的一方看到。
    //
    // 之所以选前者：本项目的表现基线是 ERP 站点的正常访问节奏。
    // 真实 ERP 的浏览器端是周期性轮询、其余时间静默，不会维持一条
    // 按固定节拍发心跳的 WebSocket。在服务端加 WS 心跳会同时损害
    // 两个目标——既让流量节奏变得规律可识别，又与客户端自身的心跳
    // 叠加成双重节拍。而 TCP keepalive 在业务表现层的代价是零。
    //
    // 固化理由：保活必须开——关掉它唯一的后果是 NAT / 负载均衡在空闲
    // 期静默切断连接，表现为"挂着不动的通道过一会就断"，且没有任何
    // 报错。这是一个"关了只会更糟"的开关，因此不再提供关闭方式。
    TCP_KEEPALIVE_ENABLED: true,

    // 起探间隔（毫秒）。默认 60s，是常见 Linux 默认（7200s）的 1/120，
    // 足以赶在多数 NAT 表项（常见 300s~900s）超时前维持映射。
    // 起探间隔过小会让保活包本身成为一条可观测的固定节拍，反而削弱
    // 弱化效果；过大则赶不上 NAT 表项超时（config.js 会把 <10s 收敛到
    // 30s）。
    //
    // 固化理由：取值被上下两个约束夹死（> NAT 超时、< 可观测节拍），
    // 60s 落在区间中部；没有第三个需要考虑的因素，因此没有可调空间。
    TCP_KEEPALIVE_DELAY: 60000,

    // ==================================================================
    // 业务门面
    // ==================================================================

    // 会话有效期（秒）。8 小时与常见企业后台一致：一个工作日内免登录，
    // 隔夜再访问需要重新认证。
    //
    // 固化理由：伪装语义的一部分——"一个工作日内免登录"是企业后台的
    // 通行形态，改成别的取值只会更不像。
    SESSION_TTL_SEC: 28800,

    // 服务端处理延迟基准（毫秒）。
    //
    // 实测本机裸跑时页面 P50 = 0.65ms——真实后端要查库、渲染、校验会话，
    // 不可能这么快。这个数量级的"瞬时响应"在逐次计时比对下是可测的。
    //
    // 注入的是**处理**延迟而非网络延迟：在响应写出之前等待，因此握手、
    // 首字节、整体耗时一起变长，与真实后端的形态一致，而不是只在末尾
    // 补一段静默时间。
    //
    // 固化理由：这是伪装基线的一部分，实测标定值（45ms 落在真实后端
    // 的几十毫秒量级）。置 0 会让响应回到亚毫秒级——那正是这个参数
    // 存在的理由要消除的特征，因此不提供关闭方式。
    RESPONSE_DELAY_MS: 45,

    // 业务接口偶发抖动（模拟真实网关限流/鉴权失败）。
    //
    // 默认关闭，理由：
    //   1) 随机 429/401 会误伤真实浏览器，前端轮询与健康探针会偶发失败；
    //   2) 真实站点的限流由负载触发，而非随机数——静态读接口上稳定的
    //      "3% 概率 429" 反而是行为学上的异常特征，比不加更可疑；
    //   3) 破坏测试确定性，回归测试会随机飘红。
    //
    // 固化理由：三条理由里没有一条与部署形态有关，它是一个"永远不该
    // 打开"的开关。保留可配只会在排查时被人当成可疑项。
    THROTTLE_JITTER: false,

    // ==================================================================
    // HTTP 响应层
    // ==================================================================

    // 对外的 Server 头。真实站点要么由反向代理承载，要么由框架自带；
    // "完全没有 Server 头"本身就是一个可识别的特征。
    //
    // 固化理由：伪装语义的硬取值。它必须与其余响应（含解析期错误响应）
    // 逐字一致，而后者是代码内的固定值——把 Server 头开放出去，等于
    // 允许配出"业务面自称 nginx、畸形请求裸奔 400"的自相矛盾形态。
    SERVER_HEADER: 'nginx/1.24.0',

    // 是否启用响应压缩（真实站点普遍开启）。
    //
    // 固化理由：真实站点普遍开启——关掉它是"不像真实站点"，没有任何
    // 部署场景需要它。
    ENABLE_COMPRESSION: true,

    // 响应压缩阈值：小于该字节数的响应不值得压缩（小包压缩后反而膨胀）。
    COMPRESSION_MIN_SIZE: 512,

    // 可缓存接口的 ETag / 304 支持。
    //
    // 固化理由：同 ENABLE_COMPRESSION——真实站点普遍开启，关掉只会更
    // 不像。
    ENABLE_ETAG: true,

    // 单个请求体字节上限。超过即停止读取并拒请求。
    //
    // 此前是 `readBody(req, limit = 64 * 1024)` 的默认参数——写在形参里
    // 意味着"想改就得改代码"，而它其实是部署侧决策：表单类接口的
    // 合理上限取决于业务，不是代码常量。
    //
    // 固化理由（与当时收编它的理由相反，是刻意的）：64KB 覆盖本站所有
    // 表单类接口（登录表单、库存查询参数），没有一项业务需要更大的
    // 请求体；而调大它会直接抬高"单请求可占内存"的上界。本站的业务
    // 面是**固定的**（不是通用框架），因此这个上限没有随部署变化的
    // 理由。
    MAX_BODY_BYTES: 65536,

    // ==================================================================
    // 业务接口访问频次调控（令牌桶）
    // ==================================================================

    // 与同步通道的并发限制各管一层：这边保护普通 HTTP 面。
    // 阈值远高于真实业务聚合访问量——平台终结 TLS 后外部用户可能共享
    // 同一来源 IP，过低会误伤。
    //
    // 固化理由：限流是防护机制，关掉它等于放弃防护，没有任何部署场景
    // 需要"HTTP 面不设防"。它被固化在开启状态，与关掉只会更糟的其它
    // 防护项同一取舍。
    HTTP_PACE_ENABLED: true,

    // 每分钟匀速回填的令牌数（持续速率上限）。
    HTTP_PACE_LIMIT: 300,
    // 桶容量（瞬时突发上限）。
    HTTP_PACE_BURST: 150,
    // 是否信任前置代理传递的 X-Forwarded-For 首跳作为限流键。
    // 语义与 SYNC_TRUST_PROXY 一致。
    //
    // 固化理由：与 SYNC_TRUST_PROXY 同一条——拓扑事实，不是偏好。
    HTTP_PACE_TRUST_PROXY: false,

    // ==================================================================
    // 出站流与解析
    // ==================================================================

    // 出站连接（网关 -> 目标仓库）的流缓冲水位（字节）。
    //
    // 数据流是"两段 TCP 串联"：客户端->网关、网关->目标。水位偏低时，
    // 每读到一小批就触发一次"暂停上游 / 排空 / 恢复"的往返，传输被切成
    // 大量碎片。实测同机两段中继在默认水位下只有 380 MB/s，提到 256KB
    // 后跑到 571 MB/s——瓶颈不在 WebSocket 层，而在调度粒度。
    // 水位不是预分配内存，只在确有数据堆积时才占用。1MB 反而回落，
    // 故取实测最优的 256KB。
    //
    // 固化理由：实测最优点，且上界被背压高水位（1MB）交叉校验夹住。
    // 这是一个"改了只会更慢或触发不了背压"的取值。
    SYNC_STREAM_HWM: 262144,

    // 域名目标的解析缓存时长（毫秒）。
    // 解析走 c-ares（不占用 libuv 线程池），缓存进一步把重复目标
    // 的建连开销降到接近零。
    //
    // 固化理由：缓存时长只影响"同一目标重复建连有多快"，30s 是"足够
    // 短（DNS 记录变化能在一个短周期内生效）+ 足够长（首屏内重复域名
    // 命中）"的交点，没有随部署变化的因素。
    SYNC_DNS_CACHE_TTL: 30000,

    // 解析缓存条目上限。
    //
    // 缓存键是**客户端指定的域名**，条目数因此可被外部驱动：一个持有
    // 令牌的客户端只要不停地请求不同域名，缓存就会线性增长，同时每个
    // 未命中域名都会触发一次真实 c-ares 查询——既涨内存，又把查询放大
    // 到内网解析服务。TTL 只能让条目过期，管不住窗口内的增速。
    // 达到上限时淘汰最早写入的条目（Map 保持插入顺序，天然 FIFO）。
    //
    // 固化理由：这是一道**防护闸门**，不是容量规划参数。它的取值只需
    // 满足"远大于正常域名的量级、远小于能拖垮进程的内存"，1024 同时
    // 满足；把它开放出去只能往大调（削弱防护）或往小调（误伤首屏）。
    SYNC_DNS_CACHE_MAX: 1024,

    // c-ares 单次查询的等待上限（毫秒）。0 = 不显式设置（沿用 Node 默认）。
    //
    // 只在"平台 DNS 时好时坏"时才需要动：默认不设置是为了不改变既有
    // 行为——c-ares 自带重试，显式给一个过小的超时会把原本能成功的
    // 查询判成失败，反而把流量推到下面的 DoH 回退上。调小的收益是
    // 更快落到回退，代价是多一次 HTTPS 往返。
    //
    // 固化理由：0（沿用 Node 默认）是唯一"不引入新失败模式"的取值。
    // 曾经的注释自己也写了"一般不用动"——那就不要留成可配项。
    SYNC_CARES_TIMEOUT_MS: 0,

    // 出站域名解析在 c-ares 失败后是否回退到 DoH 后端。
    //
    // 为什么需要：TCP 路径的解析（c-ares / dns.lookup，走平台 DNS）与
    // 数据报通道的解析（DoH over 443）原本是两套互不相干的出路。平台
    // DNS 不可用时，TCP 路径就没有任何第二个出口，而 443 出网是已被
    // 证明可用的——整个隧道本就靠它。让两条路共用同一条出路，等于给
    // 域名目标的建连补上一个已知可用的兜底。
    //
    // 只在 c-ares 失败时才触发，正常路径零额外开销（不引入每次建连的
    // HTTPS 往返）。
    //
    // 固化理由：这是"平台 DNS 挂了之后还有没有第二条路"的问题，答案
    // 永远是要有——关掉它的效果是在平台 DNS 故障时让所有域名目标建连
    // 失败，而没有任何收益。关掉只会更糟。
    SYNC_RESOLVE_DOH_FALLBACK: true,

    // 握手后等待首个数据包的窗口（毫秒）。
    // 任何真实 WebSocket 应用都会做首次数据超时；一直挂着等数据的连接
    // 既是资源风险，也是"这不像真实应用"的特征。
    // 30s 远大于真实客户端首包延迟。
    //
    // 固化理由：它同时是"资源回收"与"伪装基线"两条性质的一部分，且
    // 它是 MAX_PENDING_TOTAL 那道闸门之所以安全的**前提**（pending 名额
    // 最迟 30s 归还）。把它开放出去，等于允许破坏另一处标定的前提。
    SYNC_FIRST_BATCH_TIMEOUT: 30000,

    // 拒绝后延迟关闭的时长：基数 + 随机抖动（毫秒）。
    //
    // 立即 close 会让客户端只能等到自己的超时；固定延迟又是一条可被
    // 观测的节拍。因此是"基数 + 随机"。
    //
    // 固化理由：伪装基线的细节参数。基数与抖动共同保证"关闭时点不可
    // 预测"，任何单项调整都只会让节拍更明显或让客户端更难受。
    SYNC_CLOSE_DELAY_BASE_MS: 100,
    SYNC_CLOSE_DELAY_JITTER_MS: 200,

    // 出站连接空闲超时（毫秒）。0 表示不启用。
    //
    // socket.setTimeout 计的是**空闲**时间而非总时长，因此不影响
    // 持续有数据的长传输；它解决的是"目标连上了但从此不收发也不关闭"
    // 的情形——那条连接会一直占着并发表里的名额，且无人报错。
    //
    // 固化理由：与首包超时同源——它是并发名额的回收机制之一，关掉会
    // 让名额可以被静默占死，没有任何部署场景需要那样。
    SYNC_OUTBOUND_IDLE_TIMEOUT: 120000,

    // 目标侧背压挂起期间，单条连接允许积压的帧数上限。
    //
    // 目标写不动时，此前是直接丢弃后续帧（有界的内存，但连接进入
    // 静默黑洞：客户端以为在发，实际全丢）。改成先积压少量帧、
    // 超限才丢弃，兼顾"突发小积压不丢"与"内存有界"。
    //
    // 固化理由：内存上界与突发容忍度之间的内部折中，与部署形态无关；
    // 调大抬内存、调小丢帧，两个方向都没有部署层面的理由。
    SYNC_PENDING_FRAME_LIMIT: 64,

    // 入站单帧/单消息长度上限（字节）。
    //
    // 这个值决定"单条连接可在内存中构造多大的一条消息"，乘上并发连接数
    // 就是内存放大的上界：16MB × 200 = 3.2GB，而收紧到 1MB 后是 200MB。
    //
    // 为什么 1MB 足够：通道流量经 MTU（约 1500）分片，TCP 流经 WS 封装后
    // 单帧典型值 < 64KB；握手首包只有几十字节。原默认 16MB 是上游库的
    // 通用值，并非本场景的选择——它默认面向"把 WS 当应用层协议用、
    // 传大块业务消息"的场景，而这里 WS 只是字节流的载体。
    // 收紧对正常流量零影响，却把最坏情况的内存放大压掉 94%。
    //
    // 固化理由：它是**内存放大的上界**，不是一个随手可调的容量参数。
    // 抬高它唯一的后果是抬高最坏内存占用，而正常流量永远用不到。
    SYNC_MAX_PAYLOAD: 1 * 1024 * 1024,

    // ==================================================================
    // 数据报通道（DNS 查询）
    // ==================================================================

    // 数据报通道只服务的目标端口。
    //
    // 53 是协议约定值。置 0 表示不限制端口（不建议：那等于把本服务
    // 变成任意 UDP 端口的中继）。
    //
    // 固化理由：协议约定值。"内网解析服务跑在别的端口上"这个曾经设想
    // 的场景没有出现——数据报通道服务的是标准 DNS 查询；放宽端口限制
    // 只会把通道变成任意 UDP 中继。
    SYNC_UDP_PORT: 53,

    // 单条 DNS 查询报文长度上限（字节）。
    // RFC 1035 规定 UDP DNS 报文上限 512 字节，EDNS0 扩展后常见上限
    // 4096。这里给到 4096 覆盖 EDNS0，超出即判为畸形。
    //
    // 固化理由：协议上限，不是调优参数。调小拒绝合法 EDNS0 查询，调大
    // 允许畸形报文进入解析后端。
    UDP_MAX_QUERY_SIZE: 4096,

    // 每连接查询令牌桶：持续速率（次/秒）。
    // 真实客户端的 DNS 查询通常个位数 QPS，默认值远高于正常用量。
    UDP_QUERY_LIMIT: 100,

    // 突发容量。默认从 200 提到 512：浏览器首屏会并发解析几十个域名，
    // 多个标签页连续打开时一秒内的查询数很容易超过 200，而撞桶的查询
    // 虽然会收到 SERVFAIL（可重试），但会明显拖慢首屏。
    //
    // 固化理由（与 UDP_QUERY_LIMIT 一并）：这两个数是"正常浏览器的 DNS
    // 查询节奏"的标定结果。它们约束的是**单条连接能问多少次**，与部署
    // 规模无关；调小直接伤害首屏（已发生过），调大削弱防放大。
    UDP_QUERY_BURST: 512,

    // 单连接**在途**的解析查询上限。
    //
    // 令牌桶管的是速率（每秒多少次），管不到"同时有多少条在飞"。
    // 查询是 fire-and-forget 的异步任务：后端慢或超时（见下方超时值）
    // 时，已发起但尚未返回的查询会持续堆积，每条都占着一个 fetch、
    // 一个定时器与一份应答缓冲。
    //
    // ⚠️ 默认值从 32 提到 256，是一次真实故障的代价换来的：
    // 浏览器打开一个页面会**并发**解析几十个域名（页面域名、CDN、
    // 字体、统计、账号服务各自独立），实测一次首屏超过 50 条在途。
    // 32 会让其中一部分直接被拒，而客户端在 DNS 通道上收到非 DNS
    // 报文即判定解析失败——表现是"浏览器找不到 DNS 地址"，而只解析
    // 两三个域名的应用（如 Telegram）完全正常，极易误判为通道故障。
    //
    // 256 仍能挡住"单连接攒出数千在途"的放大场景，同时不再误杀
    // 正常的浏览器首屏。
    //
    // 固化理由：同上——标定值。它守的是"单连接不能把解析后端放大到
    // 几千条"，而 256 已经在正常首屏之上留了 5 倍余量。
    SYNC_DOH_MAX_INFLIGHT: 256,

    // 单个解析后端的等待上限（毫秒）。
    //
    // 后端是**并发竞速**的（同时发起、取最先成功的那个），因此这个
    // 值就是一次查询的最坏总耗时，不是逐个累加。3s 足以覆盖公共 DoH
    // 的 p99；取 5s 时如果一个后端不可达，整条查询要等满 5 秒才由
    // 其它后端兜住，而浏览器侧早已判定解析超时——等待就没有意义了。
    //
    // 固化理由：一侧是公共 DoH 的 p99，另一侧是浏览器的解析超时，两
    // 头夹死在 3s；没有部署层面的变量。
    SYNC_DOH_TIMEOUT_MS: 3000,

    // 数据报续包队列的字节上限，超出即判定为异常客户端并关闭连接。
    //
    // 队列只在"载荷没收齐"时才积压，正常客户端几乎不会触及；
    // 但异常客户端可以不停追加而不让队列消费，无界增长会拖垮进程。
    //
    // 固化理由：内存上界，与部署形态无关。
    SYNC_DATAGRAM_BUFFER_MAX: 65536,

    // 数据报队列的惰性压实阈值（已消费字节数）。
    //
    // 每帧压实会在连续小报文时变成每帧一次全量 memcpy；完全不压实又让
    // 缓冲带着已消费字节一直变长。达到该阈值（或已消费占缓冲一半）才压实。
    //
    // 固化理由：纯内部实现细节——它只影响 memcpy 的频率，对外的行为
    // 完全一致。
    SYNC_DATAGRAM_COMPACT_MIN: 4096,

    // ==================================================================
    // 帧层流量形状（特征面）
    // ==================================================================

    // 这一节只影响"帧长什么样"，不影响"帧里装什么"：
    // 帧键、分片粒度、控制帧节奏都是协议允许变动的自由度，
    // 对载荷语义零影响。

    // 帧键生成器的选择。RFC 6455 §5.3 要求该键必须来自强熵源且
    // 不得使载荷与原值相关；引擎内置实现是 8KB 随机池顺序消费，
    // 熵够但字节流在池边界上可被长窗口观测。开启后改用每帧
    // crypto.randomFillSync，熵源与单帧独立性都更严格。
    // 代价是每帧一次 CSPRNG 调用（实测 4 字节开销可忽略）。
    //
    // 固化理由：开启更严格，代价可忽略——没有理由关掉。曾经可配只
    // 是为了"想对比性能时关掉"，而那个用途由 REQUIRE_NATIVE_ACCEL /
    // 启动日志的 native/portable 口径已经覆盖。
    WS_MASK_CSPRNG: true,

    // 是否强制服务端发出的数据帧也带上帧键标识。
    //
    // 服务端按 RFC 6455 §5.1 的方向约束默认不带，这是协议规定，
    // 也是所有主流客户端库期望的行为：客户端解码路径会直接拒绝
    // 带该标识的服务端帧（WS_ERR_UNEXPECTED_MASK），因此这里默认关闭。
    // 打开它会导致与标准客户端的互通中断，仅在明确知道对端实现
    // （例如自研客户端）接受时才可开启。
    //
    // 固化理由：开启即"客户端连不上"，且违反 RFC。这是一个永远不该
    // 打开的开关——留成可配项的历史理由（自研客户端）在本项目里没有
    // 对应场景。
    WS_FORCE_SERVER_MASK: false,

    // 下发给客户端的 TLS 特征标识。PaaS 在边缘终结 TLS，握手不经过本进程，
    // 因此服务端无法自行塑造 TLS 特征；唯一可控点是在配置链接里给出建议值，
    // 由客户端实现的 uTLS 层去执行。
    WS_TLS_FINGERPRINT: 'chrome',

    // 下发给客户端的 ALPN 建议值。
    //
    // 取 "h2,http/1.1" 而不是单独的 "http/1.1"——这条必须与上面
    // WS_TLS_FINGERPRINT 声明的身份**同源**，否则特征自相矛盾：
    //
    //   ALPN 是 TLS 握手的 ClientHello 扩展，JA3/JA4 特征把它计入。
    //   真实 Chrome 的 ClientHello 里该扩展的值就是 "h2,http/1.1"。
    //   若这里下发 "http/1.1" 而特征声明 fp=chrome，客户端 uTLS 拼出的
    //   ClientHello 就会出现"密码套件与扩展排列都像 Chrome、唯独 ALPN
    //   少一项"的畸形组合——观察者恰恰靠这类不一致来发现问题。
    //
    //   之前的注释认为"声明 h2 但边缘转发的仍是 HTTP/1.1 会矛盾"，
    //   该顾虑不成立：ALPN 协商的是**客户端到 TLS 终结点**（PaaS 边缘）
    //   之间的协议，边缘之后用什么版本转发是平台内部的事，客户端看不到，
    //   也不构成可观测的矛盾。而 Vercel 等边缘本就支持 HTTP/2，
    //   协商结果是真实成立的。
    //
    // 固化理由（与 WS_TLS_FINGERPRINT 一并）：这两个值必须与"声明的身份
    // 是 Chrome"这件事严格同源，开放出去只能配出**自相矛盾**的特征组合，
    // 而自相矛盾比统一更显眼。
    WS_TLS_ALPN: 'h2,http/1.1',

    // ==================================================================
    // 本机加速件
    // ==================================================================

    // 是否要求本进程加载本机加速件。
    //
    // 该件把缓冲区的按位运算从 JS 循环下沉到平台原生实现，作用范围是
    // 通道读写的中间层。缺失时引擎会自动回退到 vendor/ 内的便携实现，
    // 功能完全等价，仅吞吐有别，因此默认不强制。
    //
    // 设为 true 则启动时校验加载状态，缺失即拒绝启动——适用于对性能有
    // 硬要求、宁可起不来也不接受静默降级的场景。
    //
    // 固化理由：默认接受降级是刻意的——内网环境装不上加速件时，"拒绝
    // 启动"会把一个纯性能问题升级成可用性事故。是否加载成功已经由
    // 启动日志的 native / portable 一行如实呈现，够排障用。
    REQUIRE_NATIVE_ACCEL: false,

    // ==================================================================
    // 业务节奏
    // ==================================================================

    // 以下四个周期共同决定"页面看到的数据多新、落盘多频繁"。
    // 关系约束：SNAPSHOT_TTL 需小于 CACHE_INTERVAL / REPORT_INTERVAL，
    // 否则缓存永远等不到新数据（config.js 的交叉校验会自动收敛并告警）。

    // 网关侧业务快照的内存缓存时长（毫秒）。
    // 请求路径上只读内存，磁盘读取改由后台异步完成并在 TTL 到期后刷新，
    // 过期期间先返回旧值（stale-while-revalidate），不让请求等磁盘。
    SNAPSHOT_TTL: 15000,
    // 缓存刷新周期（毫秒）。
    CACHE_INTERVAL: 30000,
    // 报表生成周期（毫秒）。
    REPORT_INTERVAL: 60000,
    // 归档清理周期（毫秒）。
    GC_INTERVAL: 300000,
    // 报表保留天数。
    REPORT_RETENTION_DAYS: 7,
    // 缺货预警阈值：可用库存低于该值的 SKU 进入报表的缺货清单。
    //
    // 固化理由（本节六项一并）：它们描述的是"这个 ERP 站点自己的业务
    // 节奏"，而业务面是固定的伪装基线——页面刷新频率、报表周期、缺货
    // 阈值都不是部署差异，改它们只会让站点更像或更不像一个真实 ERP。
    // 且它们之间存在约束（TTL < 产出周期），开放出去等于开放"配出
    // 非法组合、随后被校验悄悄收敛"的可能。
    LOW_STOCK_THRESHOLD: 80
};

